"""Train a 0-vs-1 MNIST model and export the exact FPGA coefficients."""
import argparse
import gzip
import json
from pathlib import Path

import numpy as np
from sklearn.linear_model import LogisticRegression

ROOT = Path(__file__).resolve().parent
STEPS = 32
THRESHOLD = 128


def read_split(data_dir, prefix):
    with gzip.open(data_dir / f"{prefix}-images-idx3-ubyte.gz", "rb") as source:
        pixels = np.frombuffer(source.read(), dtype=np.uint8, offset=16)
    with gzip.open(data_dir / f"{prefix}-labels-idx1-ubyte.gz", "rb") as source:
        labels = np.frombuffer(source.read(), dtype=np.uint8, offset=8)
    mask = labels < 2
    images = pixels.reshape(-1, 28, 28)[mask]
    # Average non-overlapping tiles of 3 or 4 pixels per side, rounded down.
    edges = np.arange(9) * 28 // 8
    features = np.column_stack([
        images[:, top:bottom, left:right].sum(axis=(1, 2))
        // ((bottom - top) * (right - left))
        for top, bottom in zip(edges, edges[1:])
        for left, right in zip(edges, edges[1:])
    ])
    return features.astype(np.int32), labels[mask]


def encode_input_spikes(pixels):
    potential = np.zeros_like(pixels, dtype=np.int16)
    spikes = np.empty((STEPS, *pixels.shape), dtype=bool)
    for tick in range(STEPS):
        integrated = np.maximum(potential - 1, 0) + pixels
        fired = integrated >= 256
        spikes[tick] = fired
        potential = integrated - 256 * fired
    return spikes


def spike_counts(input_spikes, weights, bias, shift):
    potential = np.zeros((input_spikes.shape[1], 2), dtype=np.int32)
    counts = np.zeros_like(potential)
    for spikes in input_spikes:
        score = spikes @ weights + bias
        drive = np.clip(score >> shift, -127, 127)
        currents = np.column_stack((128 - drive, 128 + drive))
        integrated = np.maximum(potential - 1, 0) + currents
        fired = integrated >= THRESHOLD
        potential = integrated - fired * THRESHOLD
        counts += fired
    return counts


def export(weights, bias, shift, examples):
    lines = [
        "// Generated by train.py.",
        f"localparam signed [23:0] MODEL_BIAS = 24'sh{bias & 0xffffff:06x};",
        f"localparam integer SCORE_SHIFT = {shift};",
        "function signed [7:0] weight_at;",
        "    input [5:0] address;",
        "    begin",
        "        case (address)",
    ]
    lines.extend(f"            6'd{i}: weight_at = 8'sh{int(w) & 255:02x};"
                 for i, w in enumerate(weights) if w)
    lines += ["            default: weight_at = 8'sd0;", "        endcase",
              "    end", "endfunction"]
    (ROOT / "digit_weights.vh").write_text("\n".join(lines) + "\n")
    lines = ["// Two held-out MNIST images in row-major order.",
             "function [7:0] sample_at;", "    input [6:0] address;",
             "    begin", "        case (address)"]
    lines.extend(f"            7'd{i}: sample_at = 8'd{p};"
                 for i, p in enumerate(examples.ravel()) if p)
    lines += ["            default: sample_at = 8'd0;", "        endcase",
              "    end", "endfunction"]
    (ROOT / "demo_images.vh").write_text("\n".join(lines) + "\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("data_dir", type=Path, help="Directory with four MNIST gzip files")
    args = parser.parse_args()
    x_train, y_train = read_split(args.data_dir, "train")
    x_test, y_test = read_split(args.data_dir, "t10k")
    training_rates = encode_input_spikes(x_train).mean(axis=0)
    model = LogisticRegression(max_iter=500).fit(training_rates, y_train)
    coef = model.coef_[0]
    scale = 127 / np.max(np.abs(coef))
    weights = np.rint(coef * scale).astype(np.int32)
    bias = int(np.rint(model.intercept_[0] * scale))
    scores_train = training_rates @ weights + bias
    shift = max(0, int(np.ceil(np.log2(np.percentile(abs(scores_train), 95) / 100))))
    counts = spike_counts(encode_input_spikes(x_test), weights, bias, shift)
    prediction = counts[:, 1] > counts[:, 0]
    examples = np.array([np.flatnonzero((y_test == d) & (prediction == d))[0]
                         for d in (0, 1)])
    export(weights, bias, shift, x_test[examples])
    # Check every held-out input against the integer PC implementation.

    with (ROOT / "rtl_vectors.txt").open("w") as target:
        for i in range(len(y_test)):
            target.write(" ".join(map(str, [*x_test[i], *counts[i], int(prediction[i])])) + "\n")
    report = {
        "train_images": len(y_train), "test_images": len(y_test),
        "correct": int(np.sum(prediction == y_test)),
        "accuracy": float(np.mean(prediction == y_test)),
        "ties": int(np.sum(counts[:, 0] == counts[:, 1])),
        "confusion_rows_true_cols_predicted": [
            [int(np.sum((y_test == actual) & (prediction == predicted)))
             for predicted in (0, 1)] for actual in (0, 1)
        ],
        "demo_counts": counts[examples].tolist(),
    }
    print(json.dumps(report, indent=2))


if __name__ == "__main__":
    main()


